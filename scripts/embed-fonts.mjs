// Writes fonts.css with the pixel fonts as data URLs. The plugin build has
// no loader for font files, and a data URL keeps fonts off the network.
// Run `npm run fonts` after you change a file in assets/fonts.
import { readFileSync, writeFileSync } from "node:fs";

const fonts = [
  { family: "NP Silkscreen", file: "silkscreen-400.woff2", weight: "400" },
  { family: "NP VT323", file: "vt323-400.woff2", weight: "400" },
  { family: "NP Doto", file: "doto-var.woff2", weight: "100 900" },
];

const css = fonts
  .map(({ family, file, weight }) => {
    const data = readFileSync(new URL(`../assets/fonts/${file}`, import.meta.url));
    return `@font-face {\n  font-family: "${family}";\n  font-weight: ${weight};\n  font-display: block;\n  src: url(data:font/woff2;base64,${data.toString("base64")}) format("woff2");\n}\n`;
  })
  .join("\n");

writeFileSync(
  new URL("../fonts.css", import.meta.url),
  `/* Generated by scripts/embed-fonts.mjs. Do not edit. Fonts: SIL OFL 1.1, see assets/fonts/OFL.txt. */\n${css}`,
);
